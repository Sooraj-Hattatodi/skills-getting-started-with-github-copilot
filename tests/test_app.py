def test_unregistering_twice_does_not_mutate_state(client):
    # Arrange
    activity_name = "Chess Club"
    email = activities[activity_name]["participants"][0]

    # Act
    first_response = client.delete(
        f"/activities/{activity_name}/participants/{email}"
    )
    participants_after_first_delete = activities[activity_name]["participants"].copy()
    second_response = client.delete(
        f"/activities/{activity_name}/participants/{email}"
    )

    # Assert
    assert first_response.status_code == 200
    assert second_response.status_code == 404
    assert activities[activity_name]["participants"] == participants_after_first_delete
